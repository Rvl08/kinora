//! TypeScript bindings generator.
//!
//! Produces one self-contained `.ts` file of type declarations (no runtime
//! code, no imports): every type reachable from the commands, events and
//! errors, then a `Commands` map (name → `{ args, output }`) and an `Events`
//! map (name → payload) for a typed `invoke`/`listen` wrapper in the UI.
//!
//! Output is deterministic: declarations are sorted by name and every input
//! is static, so the checked-in file changes only when the contract does.

use std::any::TypeId;
use std::collections::{BTreeMap, HashSet};
use std::fmt::Write as _;

use ts_rs::{Config, TS, TypeVisitor};

use crate::command::{CommandVisitor, visit_commands};
use crate::event::{EventVisitor, visit_events};
use crate::{IpcCommand, IpcError, IpcEvent};

/// Where the bindings live, relative to the repository root.
pub const BINDINGS_PATH: &str = "apps/desktop/ui/src/lib/ipc/bindings.ts";

/// Rendered in place of 64- and 128-bit integers. JSON numbers above 2^53
/// lose precision in JavaScript and `JSON.parse` never yields a `bigint`, so
/// such a field must be annotated `#[ts(type = "number")]` and kept within
/// 2^53 − 1 by its type; generation fails if the sentinel shows up.
const LARGE_INT_SENTINEL: &str = "__KINORA_UNANNOTATED_64_BIT_INTEGER__";

const HEADER: &str = "\
// @generated by crates/kinora-ipc (src/bindings.rs). Do not edit by hand.
// Regenerate with `cargo run -p kinora-ipc --example generate`; a test fails
// when this file is stale.
//
// Types of the IPC contract between the Kinora shell and the UI. Every
// command rejects with `IpcError`. Times are exact rationals
// (`{ num, den }` seconds); convert at the edge, never store floats.
";

/// Why the bindings could not be generated.
#[derive(Debug, PartialEq, Eq, thiserror::Error)]
pub enum BindingsError {
    /// Two different Rust types export the same TypeScript name.
    #[error(
        "two different types are both named `{0}` in TypeScript; rename one with #[ts(rename)]"
    )]
    NameCollision(String),
    /// A doc comment contains `*/`, which would end the generated JSDoc.
    #[error("generated line {0} contains `*/` inside a doc comment; reword the Rust doc comment")]
    CommentTerminator(usize),
    /// A 64- or 128-bit integer lacks a `#[ts(type = "number")]` annotation.
    #[error(
        "`{0}` contains a 64- or 128-bit integer; annotate it with #[ts(type = \"number\")] and bound it to 2^53 - 1"
    )]
    UnannotatedLargeInteger(String),
}

/// Renders the bindings file.
///
/// # Errors
/// See [`BindingsError`].
pub fn typescript() -> Result<String, BindingsError> {
    let mut collector = Collector {
        cfg: Config::default().with_large_int(LARGE_INT_SENTINEL),
        seen: HashSet::new(),
        declarations: BTreeMap::new(),
        error: None,
    };

    let mut commands = MapBuilder::default();
    visit_commands(&mut CommandCollector {
        collector: &mut collector,
        map: &mut commands,
    });
    let mut events = MapBuilder::default();
    visit_events(&mut EventCollector {
        collector: &mut collector,
        map: &mut events,
    });
    collector.visit::<IpcError>();

    if let Some(error) = collector.error {
        return Err(error);
    }

    let mut out = String::from(HEADER);
    for declaration in collector.declarations.values() {
        out.push('\n');
        out.push_str(declaration);
        out.push('\n');
    }
    out.push_str(
        "\n/** Every IPC command: `invoke(name, { args })` resolves to `output` or rejects with `IpcError`. */\n",
    );
    out.push_str(&commands.finish("Commands"));
    out.push_str("\n/** Every IPC event: `listen(name)` delivers the payload. */\n");
    out.push_str(&events.finish("Events"));
    // Catches large integers used directly as a command or event type.
    if out.contains(LARGE_INT_SENTINEL) {
        return Err(BindingsError::UnannotatedLargeInteger(
            "Commands or Events".into(),
        ));
    }
    check_comment_terminators(&out)?;
    // ts-rs leaves trailing spaces after inline field docs.
    let mut tidy = String::with_capacity(out.len());
    for line in out.lines() {
        tidy.push_str(line.trim_end());
        tidy.push('\n');
    }
    Ok(tidy)
}

/// Rust doc comments are copied into JSDoc verbatim, so a `*/` inside one
/// (`effects/*/effect.toml`) would end the comment early and break the file.
/// Every `*/` must close a comment: alone on its line, or ending a one-line
/// `/** … */`.
fn check_comment_terminators(ts: &str) -> Result<(), BindingsError> {
    for (index, line) in ts.lines().enumerate() {
        let line = line.trim();
        let closes_properly = line.ends_with("*/")
            && line.matches("*/").count() == 1
            && (line == "*/" || line.starts_with("/**"));
        if line.contains("*/") && !closes_properly {
            return Err(BindingsError::CommentTerminator(index + 1));
        }
    }
    Ok(())
}

/// Collects the declaration of every exportable type reachable from a root.
struct Collector {
    cfg: Config,
    seen: HashSet<TypeId>,
    /// TypeScript name → declaration (with its JSDoc).
    declarations: BTreeMap<String, String>,
    error: Option<BindingsError>,
}

impl TypeVisitor for Collector {
    fn visit<T: TS + 'static + ?Sized>(&mut self) {
        if self.error.is_some() || !self.seen.insert(TypeId::of::<T>()) {
            return;
        }
        // Primitives and std containers (`Option`, `Vec`, maps) have no
        // declaration of their own, but their type arguments may.
        if T::output_path().is_some() {
            self.declare::<T>();
        }
        T::visit_dependencies(self);
        T::visit_generics(self);
    }
}

impl Collector {
    fn declare<T: TS + 'static + ?Sized>(&mut self) {
        let name = T::ident(&self.cfg);
        let mut declaration = T::docs().unwrap_or_default();
        declaration.push_str("export ");
        declaration.push_str(&T::decl(&self.cfg));
        if declaration.contains(LARGE_INT_SENTINEL) {
            self.error = Some(BindingsError::UnannotatedLargeInteger(name));
            return;
        }
        // Instances of one generic type (`Animated<number>`, `Animated<Vec2>`)
        // share a single generic declaration; anything else is a collision.
        match self.declarations.get(&name) {
            Some(existing) if *existing != declaration => {
                self.error = Some(BindingsError::NameCollision(name));
            }
            Some(_) => {}
            None => {
                self.declarations.insert(name, declaration);
            }
        }
    }
}

/// Lines of a `{ name: type }` map type.
#[derive(Default)]
struct MapBuilder {
    entries: String,
}

impl MapBuilder {
    fn entry(&mut self, doc: &str, name: &str, ty: &str) {
        self.entries.push_str("  /**\n");
        for line in doc.lines() {
            let line = line.strip_prefix(' ').unwrap_or(line).replace("*/", "*\\/");
            if line.is_empty() {
                self.entries.push_str("   *\n");
            } else {
                let _ = writeln!(self.entries, "   * {line}");
            }
        }
        self.entries.push_str("   */\n");
        let _ = writeln!(self.entries, "  {}: {ty};", quote_key(name));
    }

    fn finish(self, type_name: &str) -> String {
        format!("export type {type_name} = {{\n{}}};\n", self.entries)
    }
}

/// A property key, quoted unless it is a plain identifier.
fn quote_key(name: &str) -> String {
    let plain = name.starts_with(|c: char| c.is_ascii_alphabetic() || c == '_')
        && name.chars().all(|c| c.is_ascii_alphanumeric() || c == '_');
    if plain {
        name.to_owned()
    } else {
        format!("\"{name}\"")
    }
}

struct CommandCollector<'a> {
    collector: &'a mut Collector,
    map: &'a mut MapBuilder,
}

impl CommandVisitor for CommandCollector<'_> {
    fn visit<C: IpcCommand>(&mut self) {
        self.collector.visit::<C::Args>();
        self.collector.visit::<C::Output>();
        let cfg = &self.collector.cfg;
        let ty = format!(
            "{{ args: {}; output: {} }}",
            <C::Args as TS>::name(cfg),
            <C::Output as TS>::name(cfg)
        );
        self.map.entry(C::DOC, C::NAME, &ty);
    }
}

struct EventCollector<'a> {
    collector: &'a mut Collector,
    map: &'a mut MapBuilder,
}

impl EventVisitor for EventCollector<'_> {
    fn visit<E: IpcEvent>(&mut self) {
        self.collector.visit::<E::Payload>();
        let ty = <E::Payload as TS>::name(&self.collector.cfg);
        self.map.entry(E::DOC, E::NAME, &ty);
    }
}

#[cfg(test)]
mod tests {
    use serde::Serialize;

    use super::*;

    #[test]
    fn keys_are_quoted_only_when_needed() {
        assert_eq!(quote_key("open_project"), "open_project");
        assert_eq!(quote_key("project:changed"), "\"project:changed\"");
    }

    #[test]
    fn unannotated_64_bit_integers_are_refused() {
        #[derive(Serialize, TS)]
        struct Unsafe {
            bytes: u64,
        }
        let mut collector = Collector {
            cfg: Config::default().with_large_int(LARGE_INT_SENTINEL),
            seen: HashSet::new(),
            declarations: BTreeMap::new(),
            error: None,
        };
        collector.visit::<Unsafe>();
        assert_eq!(
            collector.error,
            Some(BindingsError::UnannotatedLargeInteger("Unsafe".into()))
        );
    }

    #[test]
    fn comment_terminators_inside_docs_are_refused() {
        assert_eq!(
            check_comment_terminators("/**\n * a\n */\n/** b */\n"),
            Ok(())
        );
        assert_eq!(
            check_comment_terminators("/**\n * see effects/*/effect.toml\n */\n"),
            Err(BindingsError::CommentTerminator(2))
        );
    }

    #[test]
    fn renders_without_errors() {
        let ts = typescript().expect("renders");
        assert!(ts.starts_with("// @generated"));
        for needle in [
            "export type Project = ",
            "export type IpcError = ",
            "export type Rational = ",
            "export type Commands = {",
            "export type Events = {",
            "  apply_command: { args: ApplyCommandArgs; output: ProjectState };",
            "  \"project:changed\": ProjectChanged;",
        ] {
            assert!(ts.contains(needle), "missing {needle:?}");
        }
        assert!(!ts.contains("bigint"));
        assert!(ts.lines().all(|line| line == line.trim_end()));
    }
}
