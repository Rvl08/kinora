# Runs one job script inside Windows Sandbox and waits for it. Windows Sandbox
# allows a single instance per machine, so jobs are serialised with a lock file:
# several callers (people, agents) can invoke this at once and they queue.
#
# Why a sandbox: Smart App Control on the dev machine blocks freshly built,
# unsigned executables (Cargo build scripts, test binaries, FFmpeg's configure
# probes). The sandbox is a disposable VM without that enforcement.
#
# Usage (host):
#   powershell -ExecutionPolicy Bypass -File scripts/sandbox/invoke.ps1 -Name <job> -Script <repo-relative .ps1> [-Gpu] [-TimeoutMinutes 120]
#
# Inside the sandbox the job script runs elevated, with the repository at C:\k
# (read-write), MSVC/Windows SDK/Rust/CMake/LLVM/Node/Ninja on PATH, the VC++
# runtime installed, CARGO_TARGET_DIR=C:\b (restored from and saved to a
# persistent cache), and C:\cache for persistent downloads (e.g. MSYS2).
# Output: tests/sandbox-out/<job>/ (job.log, done.json, plus whatever the job writes to $env:JOB_OUT).
# Exit code: the job script's exit code (1 on timeout).

param(
  [Parameter(Mandatory)][ValidatePattern('^[a-z0-9][a-z0-9-]{0,40}$')][string]$Name,
  [Parameter(Mandatory)][string]$Script,
  [switch]$Gpu,
  [int]$TimeoutMinutes = 120
)
$ErrorActionPreference = 'Stop'
$repo = (Resolve-Path "$PSScriptRoot\..\..").Path
$parent = Split-Path $repo
if (-not (Test-Path (Join-Path $repo $Script))) { throw "job script not found: $Script" }
$gen = Join-Path $PSScriptRoot 'generated'
$out = Join-Path $repo "tests\sandbox-out\$Name"
New-Item -ItemType Directory -Force $gen, $out | Out-Null
Remove-Item -ErrorAction SilentlyContinue (Join-Path $out 'done.json')

# 1. Queue: take the machine-wide lock (stale after the timeout with no sandbox running).
$lock = Join-Path $parent '.kinora-sandbox.lock'
$deadline = (Get-Date).AddMinutes($TimeoutMinutes + 60)
while ($true) {
  try {
    $fs = [IO.File]::Open($lock, 'CreateNew', 'Write')
    $bytes = [Text.Encoding]::UTF8.GetBytes("$Name $PID $(Get-Date -Format o)")
    $fs.Write($bytes, 0, $bytes.Length); $fs.Close()
    break
  } catch [IO.IOException] {
    $age = (Get-Date) - (Get-Item $lock).LastWriteTime
    $running = Get-Process WindowsSandboxRemoteSession, WindowsSandboxClient -ErrorAction SilentlyContinue
    # Stale when the holder (its PID is the lock's second field) has exited, or after the timeout.
    $holderPid = 0
    [void][int]::TryParse(((Get-Content $lock -Raw) -split ' ')[1], [ref]$holderPid)
    $holderGone = $holderPid -gt 0 -and -not (Get-Process -Id $holderPid -ErrorAction SilentlyContinue)
    if (-not $running -and ($holderGone -or $age.TotalMinutes -gt $TimeoutMinutes)) { Remove-Item $lock -Force; continue }
    if ((Get-Date) -gt $deadline) { throw "gave up waiting for the sandbox lock held by: $(Get-Content $lock)" }
    Write-Host "waiting for sandbox ($(Get-Content $lock))..."
    Start-Sleep 20
  }
}

try {
  # 2. Toolchain environment, captured from vcvars64 on the host (paths are mapped 1:1 below).
  $vswhere = "${env:ProgramFiles(x86)}\Microsoft Visual Studio\Installer\vswhere.exe"
  $vs = & $vswhere -latest -products * -requires Microsoft.VisualStudio.Component.VC.Tools.x86.x64 -property installationPath
  $keep = 'INCLUDE', 'LIB', 'LIBPATH', 'VCINSTALLDIR', 'VCToolsInstallDir', 'VCToolsVersion', 'VCToolsRedistDir', 'VSINSTALLDIR',
    'WindowsSdkDir', 'WindowsSDKVersion', 'WindowsSdkBinPath', 'WindowsSdkVerBinPath', 'UCRTVersion', 'UniversalCRTSdkDir',
    'VisualStudioVersion', 'Platform', 'VSCMD_ARG_TGT_ARCH', 'VSCMD_ARG_HOST_ARCH'
  $lines = @('# Generated by scripts/sandbox/invoke.ps1. Do not commit.')
  foreach ($v in (cmd /c "call `"$(Join-Path $vs 'VC\Auxiliary\Build\vcvars64.bat')`" >nul && set")) {
    $n, $val = $v -split '=', 2
    if ($keep -contains $n) { $lines += "`$env:$n = '$($val -replace "'", "''")'" }
    if ($n -eq 'Path') {
      $tools = ($val -split ';') | Where-Object { $_ -like "$vs*" -or $_ -like '*Windows Kits*' }
      $lines += "`$env:Path = '$((($tools) -join ';') -replace "'", "''");' + `$env:Path"
    }
  }
  $llvm = if ($env:LIBCLANG_PATH) { Split-Path $env:LIBCLANG_PATH } else { 'D:\LLVM' }
  $vulkan = Get-ChildItem C:\VulkanSDK -Directory -ErrorAction SilentlyContinue | Sort-Object Name | Select-Object -Last 1
  $node = Split-Path (Get-Command node).Source
  $lines += @(
    "`$env:RUSTUP_HOME = 'C:\host\rustup'", "`$env:CARGO_HOME = 'C:\host\cargo'", "`$env:LIBCLANG_PATH = 'C:\host\llvm\bin'",
    # Ninja: the Visual Studio generator needs the VS installer's COM registration, absent in the sandbox.
    "`$env:CMAKE_GENERATOR = 'Ninja'",
    # Nested CMake projects otherwise pick the mapped LLVM's clang.
    "`$env:CC = 'cl'", "`$env:CXX = 'cl'",
    "`$env:Path = 'C:\host\cargo\bin;C:\host\cmake\bin;C:\host\llvm\bin;C:\host\node;C:\k\vendor\tools;' + `$env:Path"
  )
  if ($vulkan) { $lines += "`$env:VULKAN_SDK = '$($vulkan.FullName)'", "`$env:Path = '$($vulkan.FullName)\Bin;' + `$env:Path" }
  Set-Content -Encoding utf8 (Join-Path $gen 'env.ps1') $lines

  # 3. Sandbox definition.
  $target = Join-Path $parent 'target-sandbox'
  $cache = Join-Path $parent 'sandbox-cache'
  New-Item -ItemType Directory -Force $target, $cache | Out-Null
  function Map($h, $s, $ro) { "    <MappedFolder><HostFolder>$h</HostFolder><SandboxFolder>$s</SandboxFolder><ReadOnly>$($ro.ToString().ToLower())</ReadOnly></MappedFolder>" }
  $maps = @(
    (Map $repo 'C:\k' $false), (Map $target 'C:\t' $false), (Map $cache 'C:\cache' $false),
    (Map "$env:USERPROFILE\.rustup" 'C:\host\rustup' $false), (Map "$env:USERPROFILE\.cargo" 'C:\host\cargo' $false),
    (Map $vs $vs $true), (Map "${env:ProgramFiles(x86)}\Windows Kits\10" "${env:ProgramFiles(x86)}\Windows Kits\10" $true),
    (Map "$env:ProgramFiles\CMake" 'C:\host\cmake' $true), (Map $llvm 'C:\host\llvm' $true), (Map $node 'C:\host\node' $true)
  )
  if ($vulkan) { $maps += (Map 'C:\VulkanSDK' 'C:\VulkanSDK' $true) }
  $wsb = Join-Path $gen "$Name.wsb"
  @"
<Configuration>
  <VGpu>$(if ($Gpu) { 'Enable' } else { 'Disable' })</VGpu>
  <Networking>Enable</Networking>
  <MemoryInMB>16384</MemoryInMB>
  <MappedFolders>
$($maps -join "`n")
  </MappedFolders>
  <LogonCommand>
    <Command>powershell -ExecutionPolicy Bypass -File C:\k\scripts\sandbox\guest.ps1 -Name $Name -Script "$Script"</Command>
  </LogonCommand>
</Configuration>
"@ | Set-Content -Encoding utf8 $wsb

  # 4. Run and wait.
  $start = Get-Date
  Write-Host "sandbox job '$Name' started $(Get-Date -Format HH:mm:ss): $Script"
  Start-Process $wsb
  $done = Join-Path $out 'done.json'
  while (-not (Test-Path $done)) {
    if (((Get-Date) - $start).TotalMinutes -gt $TimeoutMinutes) {
      Get-Process WindowsSandboxRemoteSession -ErrorAction SilentlyContinue | Stop-Process -Force
      Write-Host "sandbox job '$Name' timed out after $TimeoutMinutes min"
      exit 1
    }
    Start-Sleep 10
  }
  Start-Sleep 2
  $result = Get-Content $done -Raw | ConvertFrom-Json
  # Let the VM shut down before the next job takes the lock.
  $waitEnd = (Get-Date).AddMinutes(2)
  while ((Get-Process WindowsSandboxRemoteSession -ErrorAction SilentlyContinue) -and (Get-Date) -lt $waitEnd) { Start-Sleep 3 }
  Write-Host "sandbox job '$Name' finished: exit $($result.exitCode) in $([int]((Get-Date) - $start).TotalMinutes) min; log: tests/sandbox-out/$Name/job.log"
  exit [int]$result.exitCode
} finally {
  Remove-Item $lock -Force -ErrorAction SilentlyContinue
}
