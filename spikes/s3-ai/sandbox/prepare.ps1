# Prepares a Windows Sandbox session that builds and runs Spike S3.
#
# Why: Smart App Control (enforced on the dev machine) blocks freshly built,
# unsigned executables such as Cargo build scripts. Windows Sandbox is a
# disposable VM without it, so the spike builds and runs there, with the host's
# toolchains mapped read-only and the repository mapped to the short path C:\k
# (which also keeps CMake/MSBuild paths under the 260-character limit).
#
# Usage (host):  powershell -ExecutionPolicy Bypass -File spikes/s3-ai/sandbox/prepare.ps1 [-Task "models;bench"]
# Then:          start spikes/s3-ai/sandbox/generated/kinora-s3.wsb
# Output:        tests/media/s3-out/sandbox-*.log, build.log, sandbox.done

param([string]$Task = 'models;bench', [string]$Features = '')
$ErrorActionPreference = 'Stop'
$repo = (Resolve-Path "$PSScriptRoot\..\..\..").Path
$gen = Join-Path $PSScriptRoot 'generated'
New-Item -ItemType Directory -Force $gen | Out-Null
New-Item -ItemType Directory -Force (Join-Path $repo 'tests\media\s3-out') | Out-Null

# 1. MSVC + Windows SDK environment, captured from vcvars64 on the host. The
#    Visual Studio and Windows Kits folders are mapped to the same paths inside
#    the sandbox, so the captured values stay valid there.
$vswhere = "${env:ProgramFiles(x86)}\Microsoft Visual Studio\Installer\vswhere.exe"
$vs = & $vswhere -latest -products * -requires Microsoft.VisualStudio.Component.VC.Tools.x86.x64 -property installationPath
$vcvars = Join-Path $vs 'VC\Auxiliary\Build\vcvars64.bat'
$keep = 'INCLUDE', 'LIB', 'LIBPATH', 'VCINSTALLDIR', 'VCToolsInstallDir', 'VCToolsVersion', 'VCToolsRedistDir',
  'VSINSTALLDIR', 'WindowsSdkDir', 'WindowsSDKVersion', 'WindowsSdkBinPath', 'WindowsSdkVerBinPath', 'UCRTVersion',
  'UniversalCRTSdkDir', 'VisualStudioVersion', 'Platform', 'VSCMD_ARG_TGT_ARCH', 'VSCMD_ARG_HOST_ARCH'
$vars = cmd /c "call `"$vcvars`" >nul && set"
$lines = @('# Generated by prepare.ps1 on the host. Do not commit.')
foreach ($v in $vars) {
  $name, $value = $v -split '=', 2
  if ($keep -contains $name) { $lines += "`$env:$name = '$($value -replace "'", "''")'" }
  if ($name -eq 'Path') {
    $tools = ($value -split ';') | Where-Object { $_ -like "$vs*" -or $_ -like '*Windows Kits*' }
    $lines += "`$env:Path = '$((($tools) -join ';') -replace "'", "''");' + `$env:Path"
  }
}
$lines += @(
  "`$env:RUSTUP_HOME = 'C:\host\rustup'",
  "`$env:CARGO_HOME = 'C:\host\cargo'",
  "`$env:LIBCLANG_PATH = 'C:\host\llvm\bin'",
  # Ninja, not the Visual Studio generator: that one needs the VS installer's COM
  # registration, which only exists on the host.
  "`$env:CMAKE_GENERATOR = 'Ninja'",
  # Pin MSVC for nested CMake projects too (whisper.cpp's vulkan-shaders-gen),
  # which otherwise pick the mapped LLVM's clang, too old for this MSVC STL.
  "`$env:CC = 'cl'",
  "`$env:CXX = 'cl'",
  # ggml's GGML_NATIVE probe (check_c_source_runs) fails in the sandbox and
  # silently builds without AVX; state the x86-64-v3 baseline explicitly.
  # whisper-rs-sys forwards GGML_* variables to CMake.
  "`$env:GGML_NATIVE = 'OFF'",
  "`$env:GGML_AVX = 'ON'",
  "`$env:GGML_AVX2 = 'ON'",
  "`$env:GGML_FMA = 'ON'",
  "`$env:GGML_F16C = 'ON'",
  "`$env:VULKAN_SDK = '$((Get-ChildItem C:\VulkanSDK -Directory | Sort-Object Name | Select-Object -Last 1).FullName)'",
  "`$env:Path = 'C:\host\cargo\bin;C:\host\cmake\bin;C:\host\llvm\bin;C:\k\vendor\tools;' + `$env:Path"
)
Set-Content -Encoding utf8 (Join-Path $gen 'env.ps1') $lines

# 2. The task list the sandbox runs.
Set-Content -Encoding ascii (Join-Path $repo 'tests\media\s3-out\sandbox-task.txt') $Task
Set-Content -Encoding ascii (Join-Path $repo 'tests\media\s3-out\sandbox-features.txt') $Features
Remove-Item -ErrorAction SilentlyContinue (Join-Path $repo 'tests\media\s3-out\sandbox.done')

# 3. The sandbox definition.
function Map($hostPath, $sandboxPath, $readOnly) {
  "    <MappedFolder><HostFolder>$hostPath</HostFolder><SandboxFolder>$sandboxPath</SandboxFolder><ReadOnly>$($readOnly.ToString().ToLower())</ReadOnly></MappedFolder>"
}
$targetDir = Join-Path (Split-Path $repo) 'target-s3'
New-Item -ItemType Directory -Force $targetDir | Out-Null
$llvm = if ($env:LIBCLANG_PATH) { Split-Path $env:LIBCLANG_PATH } else { 'D:\LLVM' }
$maps = @(
  (Map $repo 'C:\k' $false),
  # Build cache kept on the host so each session does not rebuild whisper.cpp and ORT.
  (Map $targetDir 'C:\t' $false),
  (Map "$env:USERPROFILE\.rustup" 'C:\host\rustup' $false),
  (Map "$env:USERPROFILE\.cargo" 'C:\host\cargo' $false),
  (Map $vs $vs $true),
  (Map "${env:ProgramFiles(x86)}\Windows Kits\10" "${env:ProgramFiles(x86)}\Windows Kits\10" $true),
  (Map "$env:ProgramFiles\CMake" 'C:\host\cmake' $true),
  (Map $llvm 'C:\host\llvm' $true),
  # Vulkan SDK (glslc) for whisper.cpp's Vulkan backend; the runtime loader comes with the GPU driver.
  (Map 'C:\VulkanSDK' 'C:\VulkanSDK' $true)
)
$wsb = @"
<Configuration>
  <VGpu>Enable</VGpu>
  <Networking>Enable</Networking>
  <MemoryInMB>16384</MemoryInMB>
  <MappedFolders>
$($maps -join "`n")
  </MappedFolders>
  <LogonCommand>
    <Command>powershell -ExecutionPolicy Bypass -File C:\k\spikes\s3-ai\sandbox\run.ps1</Command>
  </LogonCommand>
</Configuration>
"@
Set-Content -Encoding utf8 (Join-Path $gen 'kinora-s3.wsb') $wsb
Write-Host "Prepared: $gen\kinora-s3.wsb (task: $Task)"
